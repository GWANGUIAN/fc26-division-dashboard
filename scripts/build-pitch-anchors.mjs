/**
 * Measures where the head is in every cell of every field-character atlas so wearable items can follow it
 * (docs/pitch/13 §4-2). Output: src/web/pitch/data/equipmentAnchors.generated.ts.
 *
 * Per 96×96 cell (alpha >= 128): top = first row with >= 2 opaque pixels, cx = mean x of the opaque pixels in the
 * first 7 rows, w = widest opaque span of rows top+3..top+10 within ±14 px of cx. Empty cells are null.
 * Per character: headW = median w of the idle frames (row 0), used to scale items baked for `equipment.headRef`.
 *
 * Run with: pnpm build:pitch-anchors   (re-run after the atlases change; prints a QA table)
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, "..");
const manifest = JSON.parse(readFileSync(path.join(__dirname, "pitch-art-manifest.json"), "utf8"));
const atlasDir = path.join(rootDir, "src", "web", "assets", "pitch", "characters");
const outFile = path.join(rootDir, "src", "web", "pitch", "data", "equipmentAnchors.generated.ts");
const CELL = manifest.cell;
const HEAD_REF = manifest.equipment.headRef;

/** Head widths (incl. hair / ears / headphones) the automatic measurement gets wrong: the mohawk-like top of woowakgood reads as 15px. */
const HEAD_W_OVERRIDE = { woowakgood: 19 };

const median = (values) => {
  if (values.length === 0) return HEAD_REF;
  const sorted = [...values].sort((a, b) => a - b);
  return sorted[Math.floor(sorted.length / 2)];
};

function measureCell(data, width, cellX, cellY) {
  const alphaAt = (x, y) => data[((cellY + y) * width + cellX + x) * 4 + 3];
  let top = -1;
  for (let y = 0; y < CELL && top < 0; y++) {
    let count = 0;
    for (let x = 0; x < CELL; x++) if (alphaAt(x, y) >= 128) count++;
    if (count >= 2) top = y;
  }
  if (top < 0) return null;
  let sum = 0;
  let n = 0;
  for (let y = top; y < Math.min(CELL, top + 7); y++) {
    for (let x = 0; x < CELL; x++) {
      if (alphaAt(x, y) >= 128) {
        sum += x;
        n++;
      }
    }
  }
  const cx = Math.round(sum / n);
  let widest = 1;
  for (let y = top + 3; y <= Math.min(CELL - 1, top + 10); y++) {
    let lo = Infinity;
    let hi = -1;
    for (let x = Math.max(0, cx - 14); x <= Math.min(CELL - 1, cx + 14); x++) {
      if (alphaAt(x, y) >= 128) {
        lo = Math.min(lo, x);
        hi = Math.max(hi, x);
      }
    }
    if (hi >= 0) widest = Math.max(widest, hi - lo + 1);
  }
  return [cx, top, widest];
}

const entries = [];
const table = [];
for (const id of manifest.characters.field) {
  const file = path.join(atlasDir, `${id}-atlas.webp`);
  if (!existsSync(file)) {
    console.warn(`? atlas not found: ${file}`);
    continue;
  }
  const { data, info } = await sharp(file).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const cells = [];
  for (let row = 0; row < info.height / CELL; row++) {
    for (let col = 0; col < info.width / CELL; col++) cells.push(measureCell(data, info.width, col * CELL, row * CELL));
  }
  const idle = [0, 1, 2, 3, 4, 5].map((i) => cells[i]).filter(Boolean).map((cell) => cell[2]);
  const headW = HEAD_W_OVERRIDE[id] ?? median(idle);
  const empty = cells.filter((cell) => !cell).length;
  table.push(`${id.padEnd(14)} headW ${String(headW).padStart(2)}  cells ${cells.length - empty}/${cells.length}  idle tops ${[0, 2, 4].map((i) => cells[i]?.[1]).join("/")}`);
  entries.push(`  ${JSON.stringify(id)}: { headW: ${headW}, cells: [${cells.map((cell) => (cell ? `[${cell.join(",")}]` : "null")).join(",")}] },`);
}

const text = [
  "// GENERATED by scripts/build-pitch-anchors.mjs — do not edit. Head position of every atlas cell (docs/pitch/13 §4-2).",
  "// cells[row * 10 + col] = [head centre x, head top y, head width] in cell px, or null for an empty cell.",
  `export const HEAD_REF = ${HEAD_REF};`,
  "",
  "export interface CharacterAnchors {",
  "  /** Median head width of the idle frames, px. */",
  "  headW: number;",
  "  cells: ReadonlyArray<readonly [number, number, number] | null>;",
  "}",
  "",
  "export const CHARACTER_ANCHORS: Readonly<Record<string, CharacterAnchors>> = {",
  ...entries,
  "};",
  "",
].join("\n");
writeFileSync(outFile, text);
console.log(table.join("\n"));
console.log(`wrote ${path.relative(rootDir, outFile)} (${entries.length} characters)`);
