/**
 * Easter-egg generator: converts the local woowakgood.webp (from ~/Downloads)
 * and every roster streamer's SOOP profile image into small ASCII art strings,
 * then bakes them into a generated TS module so the site can console.log them
 * without fetching/converting anything at runtime.
 *
 * Run with: pnpm generate:ascii-art
 */
import { readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parse as parseYaml } from "yaml";
import sharp from "sharp";
import asciify from "asciify-image";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, "..");

// Note: asciify-image renders each resized pixel as `c_ratio` (default 2)
// characters wide to correct for monospace font aspect ratio, so the actual
// printed width is roughly 2x the `width` option below.
const BANNER_ASCII_OPTIONS = { fit: "width", width: 50, color: false };
const PROFILE_ASCII_OPTIONS = { fit: "width", width: 60, color: false };

const defaultSoopProfileUrl = (soopId) =>
  `https://stimg.sooplive.com/LOGO/${encodeURIComponent(soopId.slice(0, 2).toLowerCase())}/${encodeURIComponent(soopId)}/m/${encodeURIComponent(soopId)}.webp`;

async function webpBufferToAscii(webpBuffer, options) {
  const pngBuffer = await sharp(webpBuffer).png().toBuffer();
  return asciify(pngBuffer, options);
}

async function fetchProfileAscii(soopId) {
  const url = defaultSoopProfileUrl(soopId);
  const res = await fetch(url);
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  const buffer = Buffer.from(await res.arrayBuffer());
  return webpBufferToAscii(buffer, PROFILE_ASCII_OPTIONS);
}

async function mapWithConcurrency(items, limit, fn) {
  const results = new Array(items.length);
  let cursor = 0;
  async function worker() {
    while (cursor < items.length) {
      const index = cursor++;
      results[index] = await fn(items[index], index);
    }
  }
  await Promise.all(Array.from({ length: limit }, worker));
  return results;
}

async function main() {
  console.log("Converting woowakgood.webp...");
  const woowakgoodPath = path.join(homedir(), "Downloads", "woowakgood.webp");
  const woowakgoodBuffer = readFileSync(woowakgoodPath);
  const woowakgoodAscii = await webpBufferToAscii(woowakgoodBuffer, BANNER_ASCII_OPTIONS);

  const rosterText = readFileSync(path.join(rootDir, "roster.yaml"), "utf8");
  const roster = parseYaml(rosterText).streamers;
  const soopIds = [...new Set(
    roster
      .filter((entry) => !entry.deleted && entry.soopId)
      .map((entry) => String(entry.soopId).trim())
      .filter(Boolean),
  )];

  console.log(`Converting ${soopIds.length} streamer profile images...`);
  const entries = await mapWithConcurrency(soopIds, 6, async (soopId) => {
    try {
      const ascii = await fetchProfileAscii(soopId);
      process.stdout.write(".");
      return [soopId, ascii];
    } catch (err) {
      process.stdout.write("x");
      console.warn(`\nSkipping ${soopId}: ${err.message}`);
      return null;
    }
  });
  console.log("");

  const streamerAsciiArt = Object.fromEntries(entries.filter(Boolean));

  const outPath = path.join(rootDir, "src", "web", "asciiArt.generated.ts");
  const header = [
    "// AUTO-GENERATED by scripts/generate-ascii-art.mjs — do not edit by hand.",
    "// Regenerate with: pnpm generate:ascii-art",
    "",
  ].join("\n");
  const body = [
    `export const WOOWAKGOOD_ASCII_ART = ${JSON.stringify(woowakgoodAscii)};`,
    "",
    `export const STREAMER_ASCII_ART: Record<string, string> = ${JSON.stringify(streamerAsciiArt, null, 2)};`,
    "",
  ].join("\n");
  writeFileSync(outPath, header + body);

  console.log(`Wrote ${Object.keys(streamerAsciiArt).length} profile art entries to ${path.relative(rootDir, outPath)}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
